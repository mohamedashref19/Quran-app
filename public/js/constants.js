/**
 * جيب اسم السورة من رقم الصفحة
 * @param {number} pageNum - رقم الصفحة (1-604)
 * @returns {string} اسم السورة
 */
export const getSurahNameByPage = (pageNum) => {
  let idx = 0;
  for (let i = 0; i < surahPageMap.length; i++) {
    if (surahPageMap[i] <= pageNum) idx = i;
    else break;
  }
  return surahNames[idx] || "الفاتحة";
};

/**
 * جيب رقم الجزء من رقم الصفحة
 * @param {number} pageNum - رقم الصفحة (1-604)
 * @returns {number} رقم الجزء (1-30)
 */
export const getJuzByPage = (pageNum) => {
  let juz = 1;
  for (let i = 0; i < juzData.length; i++) {
    if (juzData[i].page <= pageNum) juz = juzData[i].juz;
    else break;
  }
  return juz;
};

/**
 
 * @param {number} pageNum - رقم الصفحة (1-604)
 * @returns {number} رقم الحزب (1-60)
 */
export const getHizbByPage = (pageNum) => {
  let hizb = 1;
  for (let i = 0; i < hizbStartPages.length; i++) {
    if (hizbStartPages[i] <= pageNum) hizb = i + 1;
    else break;
  }
  return hizb;
};




